// ---- деньги и вес ----
const nf0 = new Intl.NumberFormat('ru-RU', { maximumFractionDigits: 0 })
export const olRub = (n: number) => `${nf0.format(Math.round(n))} ₽`
export const olGrams = (g: number) => (g >= 1000 ? `${String(g / 1000).replace('.', ',')} кг` : `${g} г`)
// Вес по умолчанию — первая фасовка; у весовых позиций цена = ₽/кг × вес (так считает их WooCommerce)
export const olBaseG = (p: OlProduct) => (p.w ? p.w.g[0] : 0)
export const olPrice = (p: OlProduct, g = 0) => (p.w && g ? Math.round((p.w.kg * g) / 1000) : p.p)
export const olOld = (p: OlProduct, g = 0) => (p.op ? Math.round(olPrice(p, g) * (p.op / p.p)) : 0)
export const olDisc = (p: OlProduct) => (p.op > p.p ? Math.round((1 - p.p / p.op) * 100) : 0)
export const olUnit = (p: OlProduct, g = 0) => (p.w ? olGrams(g || p.w.g[0]) : p.u.replace(' ', ' '))
export const olCountText = (n: number) => {
  const a = n % 10
  const b = n % 100
  const w = a === 1 && b !== 11 ? 'товар' : a >= 2 && a <= 4 && (b < 10 || b >= 20) ? 'товара' : 'товаров'
  return `${n} ${w}`
}

export const olProduct = (id: string) => olProducts.find((p) => p.id === id)
export const olBySection = (sec: string, sub = '') =>
  sec === 'sale' ? olProducts.filter((p) => p.op > 0) : olProducts.filter((p) => p.sec === sec && (!sub || p.sub === sub))
export const olSearch = (q: string, limit = 50) => {
  const words = q.toLowerCase().replace(/ё/g, 'е').split(/\s+/).filter(Boolean)
  if (!words.length) return []
  return olProducts
    .filter((p) => {
      const s = `${p.full} ${olSection(p.sec)?.name ?? ''}`.toLowerCase().replace(/ё/g, 'е')
      return words.every((w) => s.includes(w.slice(0, Math.max(3, w.length - 2))))
    })
    .slice(0, limit)
}

