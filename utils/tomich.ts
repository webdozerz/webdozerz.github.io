/** Дата доставки заказа, оформленного сейчас: завтра по томскому времени. */
export const tmDeliveryDate = (now = new Date()) => {
  const tomorrow = new Date(now.getTime() + 24 * 60 * 60 * 1000)
  const fmt = (opts: Intl.DateTimeFormatOptions) =>
    new Intl.DateTimeFormat('ru-RU', { timeZone: 'Asia/Tomsk', ...opts }).format(tomorrow)
  return { day: fmt({ day: 'numeric', month: 'long' }), weekday: fmt({ weekday: 'long' }) }
}

