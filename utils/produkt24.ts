// Вес одной штуки/упаковки из названия: «Гуляш 0,8кг/12шт» → 0,8 кг, «Мука 2кг» → 2 кг, «Тушёнка 325г» → 0,325.
export const pkWeightPer = (p: PkProduct) => {
  if (p.unit === 'кг') return 1
  const m = p.name.match(/(\d+(?:[.,]\d+)?)\s*(кг|гр|г)(?![а-я])/i)
  if (!m) return 0
  const v = Number(m[1].replace(',', '.'))
  return m[2].toLowerCase() === 'кг' ? v : v / 1000
}

const norm = (s: string) => s.toLowerCase().replace(/ё/g, 'е').replace(/[«»"()]/g, ' ')
const index = pkProducts.map((p) => norm(`${p.name} ${p.group}`))
// Все слова запроса должны встретиться в названии или группе; короткие окончания отрезаем — «тушенки» найдёт «тушенка».
export const pkSearch = (q: string, list: PkProduct[] = pkProducts) => {
  const words = norm(q)
    .split(/\s+/)
    .filter(Boolean)
    .map((w) => (w.length > 4 ? w.slice(0, w.length - 1) : w))
  if (!words.length) return list
  return list.filter((p) => {
    const text = index[pkProducts.indexOf(p)]
    return words.every((w) => text.includes(w))
  })
}

