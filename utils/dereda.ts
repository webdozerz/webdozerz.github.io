// Доставка по вторникам и пятницам; приём заказов на вторник — до 23:59 воскресенья, на пятницу — до 23:59 среды. Время Новосибирска (UTC+7).
const TZ = 7 * 3600e3
const DAY = 86400e3
const WD_ACC = ['воскресенье', 'понедельник', 'вторник', 'среду', 'четверг', 'пятницу', 'субботу']
const WD_SHORT = ['вс', 'пн', 'вт', 'ср', 'чт', 'пт', 'сб']
const MONTHS = ['января', 'февраля', 'марта', 'апреля', 'мая', 'июня', 'июля', 'августа', 'сентября', 'октября', 'ноября', 'декабря']
export interface DrDelivery {
  key: string
  wd: number
  day: number
  month: number
  // конец приёма — момент времени (мс)
  until: number
  untilWd: number
  label: string
  short: string
  untilLabel: string
}
export const drDeliveries = (now: number, n = 4): DrDelivery[] => {
  const loc = new Date(now + TZ)
  const base = Date.UTC(loc.getUTCFullYear(), loc.getUTCMonth(), loc.getUTCDate())
  const out: DrDelivery[] = []
  for (let i = 0; out.length < n && i < 30; i++) {
    const d = new Date(base + i * DAY)
    const wd = d.getUTCDay()
    if (wd !== 2 && wd !== 5) continue
    const until = base + i * DAY - 2 * DAY + DAY - 1000 - TZ
    if (now > until) continue
    const untilWd = wd === 2 ? 0 : 3
    out.push({
      key: `${d.getUTCFullYear()}-${d.getUTCMonth() + 1}-${d.getUTCDate()}`,
      wd,
      day: d.getUTCDate(),
      month: d.getUTCMonth(),
      until,
      untilWd,
      label: `${WD_ACC[wd]}, ${d.getUTCDate()} ${MONTHS[d.getUTCMonth()]}`,
      short: `${WD_SHORT[wd]}, ${d.getUTCDate()} ${MONTHS[d.getUTCMonth()].slice(0, 3)}`,
      untilLabel: `до 23:59 ${WD_SHORT[untilWd]}`,
    })
  }
  return out
}
export const drLeft = (ms: number) => {
  const m = Math.max(0, Math.floor(ms / 60000))
  const d = Math.floor(m / 1440)
  const h = Math.floor((m % 1440) / 60)
  const mm = m % 60
  if (d) return `${d} д ${h} ч`
  if (h) return `${h} ч ${mm} мин`
  return `${mm} мин`
}

export const drMoney = (n: number) => `${Math.round(n).toLocaleString('ru-RU')} ₽`
export const drPlural = (n: number, one: string, few: string, many: string) => {
  const a = Math.abs(n) % 100
  const b = a % 10
  if (a > 10 && a < 20) return many
  if (b > 1 && b < 5) return few
  if (b === 1) return one
  return many
}

