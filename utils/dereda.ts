export const drProduct = (id: string) => drProducts.find((p) => p.id === id)
export const drSection = (id: string) => drSections.find((s) => s.id === id)
export const drFarmer = (id: string | null) => (id ? drFarmers.find((f) => f.id === id) : undefined)
export const drFarmerProducts = (id: string) => drProducts.filter((p) => p.farmer === id)
export const drSecProducts = (id: string) => drProducts.filter((p) => p.sec === id)
// Подразделы, у которых в выборке концепта есть товары (пустые не показываем)
export const drSubsOf = (id: string) => (drSection(id)?.subs ?? []).filter((x) => drProducts.some((p) => p.sec === id && p.sub === x.title))
// Фото раздела — первый товар раздела с фото
export const drSecImg = (id: string) => drSecProducts(id).find((p) => p.stock !== 'out')?.img ?? drSecProducts(id)[0]?.img ?? ''
export const drFarmerImg = (id: string) => drFarmers.find((f) => f.id === id)?.photo ?? drFarmerProducts(id)[0]?.img ?? ''
// Цена и старая цена выбранной фасовки
export const drPriceOf = (p: DrProduct, v = 0) => p.variants[v]?.price ?? p.price
export const drOldOf = (p: DrProduct, v = 0) => {
  const o = p.variants.length ? p.variants[v]?.old : p.old
  const pr = drPriceOf(p, v)
  return o && o > pr ? o : null
}
export const drPackOf = (p: DrProduct, v = 0) => p.variants[v]?.t ?? p.pack
export const drAvailable = (p: DrProduct, v = 0) =>
  p.variants.length ? p.variants[v]?.on !== false && p.stock !== 'out' : p.stock !== 'out'
export const drFirstOn = (p: DrProduct) =>
  Math.max(
    0,
    p.variants.findIndex((x) => x.on),
  )
export const drDiscount = (p: DrProduct, v = 0) => {
  const o = drOldOf(p, v)
  return o ? Math.round((1 - drPriceOf(p, v) / o) * 100) : 0
}
// Вес «±» в названии — значит весовой товар, сумма уточняется после взвешивания
export const drWeighed = (p: DrProduct) => /\+\/-|~/.test(p.title)
export const drShort = (t: string) => t.replace(/\s*\+\/-\s*\d+\s*гр/, '').replace(/~/g, '≈ ')
